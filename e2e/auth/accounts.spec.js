async function signIn(page, account) {
  await page.goto('/login')
  await page.getByLabel('Email', { exact: true }).fill(account.email)
  await page.getByLabel('Password', { exact: true }).fill('password-123')
  await activate(page, page.getByRole('button', { name: 'Log in', exact: true }))
  await expect(page.getByRole('link', { name: 'Account data', exact: true })).toBeVisible()
  await expect(page.getByText(`${account.email} · Guest plans stay separate on this device.`, { exact: true })).toBeVisible()
}
async function uploadPixels(page) {
  const encoded = await page.evaluate(() => {
    const canvas = document.createElement('canvas')
    canvas.width = canvas.height = 4
    canvas.getContext('2d').fillRect(0, 0, 4, 4)
    return canvas.toDataURL('image/png').split(',')[1]
  })
  await page.locator('input[type=file]').setInputFiles({ name: 'cloud.png', mimeType: 'image/png', buffer: Buffer.from(encoded, 'base64') })
}

